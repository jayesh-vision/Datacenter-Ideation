import { chromium } from 'playwright';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errs.push(m.text()); });
await p.goto('http://localhost:5181/capacity', { waitUntil: 'networkidle' }); await p.waitForTimeout(500);
const before = await p.locator('.plan-row').count();
await p.locator('button:has-text("Raise capacity plan")').first().click(); await p.waitForTimeout(500);
await p.locator('.modal select').nth(0).selectOption('KA-DC-020');
await p.locator('.modal select').nth(1).selectOption('Cooling');
await p.locator('.modal input[type=number]').fill('150'); await p.waitForTimeout(400);
const ba = await p.locator('.modal .ba').innerText();
console.log('what-if:', ba.replace(/\n/g, ' | '));
console.log('chips:', (await p.locator('.modal .row.wrap').innerText()).replace(/\n/g, ' | '));
await p.screenshot({ path: '.qa/out/cap-modal.png' });
await p.locator('.modal button:has-text("Submit plan")').click(); await p.waitForTimeout(800);
console.log('url', p.url());
const titles = await p.locator('.plan-row b').allInnerTexts();
console.log('ledger has new plan:', titles.some(t => t.includes('cooling capacity at KA-DC-020')), titles.length);
await p.goto('http://localhost:5181/capacity?tab=power', { waitUntil: 'networkidle' });
await p.locator('.seg button', { hasText: 'All racks' }).click(); await p.waitForTimeout(300);
console.log('racks all pager:', await p.locator('.dt-pager span').first().innerText().catch(() => 'n/a'));
console.log(errs.length ? 'ERR ' + errs.join(' | ') : 'no console errors'); await b.close();
