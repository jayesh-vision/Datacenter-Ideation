import { chromium } from 'playwright';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
const ok = (n, c) => console.log(c ? 'PASS' : 'FAIL', n);
await p.goto('http://localhost:5181/ne/MH-DC-001-PE-T4-01?tab=links', { waitUntil: 'networkidle' }); await p.waitForTimeout(500);
await p.locator('.ne-proto-card', { hasText: 'BGP' }).click(); await p.waitForTimeout(200);
ok('protocol filter', (await p.locator('.dt-toolbar').first().innerText()).includes('BGP links'));
await p.locator('tbody tr').first().click(); await p.waitForTimeout(500);
ok('link drawer', await p.locator('.drawer').count() === 1 && (await p.locator('.drawer').innerText()).includes('Protocols on this span'));
await p.screenshot({ path: '.qa/out/ne-drawer.png' });
await p.keyboard.press('Escape');
await p.locator('.ne-fc-item').nth(1).click(); await p.waitForTimeout(300);
ok('countdown select → url', p.url().includes('if='));
await p.goto('http://localhost:5181/ne/MH-DC-001-PE-T4-01?tab=alerts', { waitUntil: 'networkidle' }); await p.waitForTimeout(500);
const before = await p.locator('button:has-text("Acknowledge")').count();
await p.locator('button:has-text("Acknowledge")').first().click(); await p.waitForTimeout(500);
ok('acknowledge', await p.locator('button:has-text("Acknowledge")').count() === before - 1);
await p.locator('select').first().selectOption('minor'); await p.waitForTimeout(200);
ok('severity filter', (await p.locator('.ne-alert').count()) === 4);
await p.locator('select').first().selectOption('');
await p.locator('.ne-alert', { hasText: 'BGP Peer Idle' }).locator('.check').click();
await p.locator('.ne-alert', { hasText: 'Temperature Warning' }).locator('.check').click();
await p.locator('button:has-text("Correlate into incident")').click(); await p.waitForTimeout(800);
ok('correlate → incident page ' + p.url(), /\/incidents\/INC-\d+/.test(p.url()));
await p.goto('http://localhost:5181/ne/MH-DC-001-PE-T4-01', { waitUntil: 'networkidle' }); await p.waitForTimeout(400);
await p.locator('button:has-text("Node resources")').click(); await p.waitForTimeout(300);
ok('node resources', (await p.locator('.drawer').innerText()).includes('Routing Engine'));
console.log(errs.length ? 'ERRORS ' + errs.join(' | ') : 'no console errors'); await b.close();
